#!/usr/bin/env python3
"""
gen_data.py
Generates data.h with:
  - Two random float matrices A (MxN) and B (MxN)
  - TCDM float pointers x, y, out
  - Golden model: out_golden[i][j] = A[i][j] + B[i][j]  (residual)
"""

import numpy as np
import argparse
from pathlib import Path

# ── CLI args ──────────────────────────────────────────────────────────────────
SCRIPT_DIR = Path(__file__).resolve().parent

parser = argparse.ArgumentParser(description="Generate data.h for residual kernel")
parser.add_argument("-M", type=int, default=64,  help="Number of rows    (default 64)")
parser.add_argument("-N", type=int, default=64, help="Number of columns (default 64)")
parser.add_argument("-o", "--output", default=str(SCRIPT_DIR / "data.h"),
                    help="Output header file (default: <script_dir>/data.h)")
parser.add_argument("--seed", type=int, default=42, help="Random seed (default 42)")
args = parser.parse_args()

M, N = args.M, args.N
rng  = np.random.default_rng(args.seed)

# ── Generate matrices ─────────────────────────────────────────────────────────
A      = rng.uniform(-1.0, 1.0, (M, N)).astype(np.float32)
B      = rng.uniform(-1.0, 1.0, (M, N)).astype(np.float32)
Golden = (A + B).astype(np.float32)          # residual (element-wise sum)

# ── Helper: numpy 2-D array → C float array literal ──────────────────────────
def matrix_to_c(name: str, mat: np.ndarray) -> str:
    rows, cols = mat.shape
    lines = [f"float {name}[{rows}*{cols}] = {{"]
    flat  = mat.flatten()
    # 8 values per line for readability
    chunk = 8
    for i in range(0, len(flat), chunk):
        vals = ", ".join(f"{v:.8e}f" for v in flat[i:i+chunk])
        lines.append(f"    {vals},")
    # strip trailing comma on last element
    lines[-1] = lines[-1].rstrip(",")
    lines.append("};")
    return "\n".join(lines)

# ── Write header ──────────────────────────────────────────────────────────────
with open(args.output, "w") as f:
    f.write(f"""\
#ifndef DATA_H
#define DATA_H

/* Auto-generated by gen_data.py
 * M={M}, N={N}, seed={args.seed}
 * Matrices stored in row-major order, shape [{M}][{N}]
 * Golden model: golden[i*N+j] = mat_a[i*N+j] + mat_b[i*N+j]  (residual)
 */

#ifndef M
#define M {M}
#endif

#ifndef N
#define N {N}
#endif

/* ── TCDM pointers (set at runtime by the DMA / init code) ──────────────── */
float *x;        /* points to mat_a in TCDM  */
float *y;        /* points to mat_b in TCDM  */
float *out;      /* points to output in TCDM */

/* ── Input matrices (L2 / flash) ────────────────────────────────────────── */
{matrix_to_c("mat_a", A)}

{matrix_to_c("mat_b", B)}

/* ── Golden model (residual = element-wise sum) ─────────────────────────── */
{matrix_to_c("golden", Golden)}

#endif /* DATA_H */
""")

print(f"[gen_data.py] Written '{args.output}'  (M={M}, N={N}, {M*N} elements each matrix)")