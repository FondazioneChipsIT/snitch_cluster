# Generate data/data.h for the Layer Normalisation kernel.
# Run from anywhere:
#   python sw/benchmarks/LLM/layernorm/scripts/datagen.py

import numpy as np
import os

# ──────────────────────────────────────────────
#  Configuration
# ──────────────────────────────────────────────
BATCH_SIZE    = 1      # number of independent sequences in the batch
SEQ_LEN       = 8      # number of tokens per sequence (must be divisible by
                       # the number of compute cores, typically 8)
EMBEDDINGS    = 32     # embedding / hidden dimension (must be divisible by
                       # UNROLL * 2 = 8 when using the SIMD kernel,
                       # or by UNROLL = 4 for the scalar kernel)

EPS           = 1e-5   # epsilon added to the variance for numerical stability
BASELINE      = 0      # 0 = SSR-optimised kernel, 1 = naive reference
CHECK_RESULTS = 1
SEED          = 42     # set to None for a random seed
# ──────────────────────────────────────────────

assert SEQ_LEN   >= 1,          "SEQ_LEN must be >= 1"
assert EMBEDDINGS >= 1,          "EMBEDDINGS must be >= 1"
assert EMBEDDINGS % 4 == 0,     "EMBEDDINGS must be divisible by UNROLL (4)"

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))


def layernorm_golden(x: np.ndarray, eps: float) -> np.ndarray:
    """
    Layer normalisation along the last (embedding) dimension.

    x : (batch_size, seq_len, embeddings)  float64 for accuracy
    returns output of the same shape, cast to float32
    """
    mean = x.mean(axis=-1, keepdims=True)               # (B, S, 1)
    var  = x.var(axis=-1,  keepdims=True)               # (B, S, 1)
    out  = (x - mean) / np.sqrt(var + eps)
    return out.astype(np.float32)


def fmt_float(v: float) -> str:
    return repr(float(v))


def write_c_array(f, name: str, data: np.ndarray, dtype_decl: str = "float",
                  align: int = 4096, extern: bool = False) -> None:
    flat = data.flatten()
    n    = len(flat)
    if extern:
        f.write(f"extern {dtype_decl} {name}[{n}]"
                f" __attribute__ ((aligned ({align})));\n\n")
        return
    f.write(f"{dtype_decl} {name}[{n}]"
            f" __attribute__ ((aligned ({align}))) = {{\n")
    for v in flat:
        f.write(f"\t{fmt_float(v)},\n")
    f.write("};\n\n")


def main():
    rng = np.random.default_rng(SEED)

    # Generate input: (batch_size, seq_len, embeddings), cast to fp32
    input_data = rng.standard_normal(
        (BATCH_SIZE, SEQ_LEN, EMBEDDINGS)
    ).astype(np.float32)

    # Golden reference computed in float64 for accuracy
    O_golden = layernorm_golden(input_data.astype(np.float64), EPS)

    out_dir  = os.path.normpath(os.path.join(SCRIPT_DIR, "..", "data"))
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "data.h")

    # Total number of elements per matrix
    total = BATCH_SIZE * SEQ_LEN * EMBEDDINGS

    with open(out_path, "w") as f:
        # ── Licence & pragma ────────────────────────────────────────────────
        f.write("// Copyright 2026 ETH Zurich and University of Bologna.\n")
        f.write("// Licensed under the Apache License, Version 2.0,"
                " see LICENSE for details.\n")
        f.write("// SPDX-License-Identifier: Apache-2.0\n")
        f.write("//\n")
        f.write("// Auto-generated by datagen_layernorm.py"
                " — do not edit manually.\n\n")
        f.write("#pragma once\n\n")

        # ── Compile-time parameters ──────────────────────────────────────────
        f.write(f"#define BATCH_SIZE    {BATCH_SIZE}\n")
        f.write(f"#define SEQ_LEN       {SEQ_LEN}\n")
        f.write(f"#define EMBEDDINGS    {EMBEDDINGS}\n")
        f.write(f"#define BASELINE      {BASELINE}\n")
        f.write(f"#define CHECK_RESULTS {CHECK_RESULTS}\n\n")
        f.write(f"float EPS           = 1e-5f;\n\n")

        # ── Forward declarations ─────────────────────────────────────────────
        write_c_array(f, "input",  input_data, extern=True)

        # Output buffer: uninitialised, same shape as input
        f.write(f"float output[{total}]"
                f" __attribute__ ((aligned (4096)));\n\n")

        # ── Data definitions ─────────────────────────────────────────────────
        write_c_array(f, "input",    input_data)
        write_c_array(f, "O_golden", O_golden)

    print(f"Generated {out_path}")
    print(f"  BATCH_SIZE={BATCH_SIZE}  SEQ_LEN={SEQ_LEN}"
          f"  EMBEDDINGS={EMBEDDINGS}  EPS={EPS}"
          f"  ({total} elements per matrix)")


if __name__ == "__main__":
    main()