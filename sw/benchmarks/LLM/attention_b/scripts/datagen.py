# Generate data/data.h for the Flash Attention 2 kernel.
# Run from anywhere:
#   python sw/benchmarks/LLM/flashattention/scripts/datagen.py

import numpy as np
import os

# ──────────────────────────────────────────────
#  Configuration
# ──────────────────────────────────────────────
L         = 64    # sequence length (rows of Q / O)
S         = 64    # key/value length (rows of K / V)
D         = 64    # head dimension
B_R       = 16    # row block size    (must divide L)
B_C       = 16    # column block size (must divide S)
BASELINE  = 0     # 0 = SSR-optimised, 1 = naive GEMM
CHECK_RESULTS = 1
SEED      = 42    # set to None for a random seed
# ──────────────────────────────────────────────

assert L % B_R == 0, "L must be divisible by B_R"
assert S % B_C == 0, "S must be divisible by B_C"

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))


def attention_golden(Q: np.ndarray, K: np.ndarray, V: np.ndarray) -> np.ndarray:
    """Standard scaled dot-product attention (no scale factor, matches kernel)."""
    S_mat = Q @ K.T                                        # (L, S)
    S_mat -= S_mat.max(axis=-1, keepdims=True)             # numerical stability
    P = np.exp(S_mat)
    P /= P.sum(axis=-1, keepdims=True)
    return (P @ V).astype(np.float32)                     # (L, D)


def fmt_float(v: float) -> str:
    return repr(float(v))


def write_c_array(f, name: str, data: np.ndarray, dtype_decl: str = "float",
                  align: int = 4096, extern: bool = False) -> None:
    flat = data.flatten()
    n    = len(flat)
    if extern:
        f.write(f"extern {dtype_decl} {name}[{n}]"
                f" __attribute__ ((aligned ({align})));\n\n")
        return
    f.write(f"{dtype_decl} {name}[{n}]"
            f" __attribute__ ((aligned ({align}))) = {{\n")
    for v in flat:
        f.write(f"\t{fmt_float(v)},\n")
    f.write("};\n\n")


def main():
    rng = np.random.default_rng(SEED)

    Q = rng.random((L, D), dtype=np.float64).astype(np.float32)
    K = rng.random((S, D), dtype=np.float64).astype(np.float32)
    V = rng.random((S, D), dtype=np.float64).astype(np.float32)
    O_golden = attention_golden(Q.astype(np.float64),
                                K.astype(np.float64),
                                V.astype(np.float64))

    out_dir  = os.path.normpath(os.path.join(SCRIPT_DIR, "..", "data"))
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "data.h")

    with open(out_path, "w") as f:
        # ── Licence & pragma ────────────────────────────────────────────────
        f.write("// Copyright 2026 ETH Zurich and University of Bologna.\n")
        f.write("// Licensed under the Apache License, Version 2.0,"
                " see LICENSE for details.\n")
        f.write("// SPDX-License-Identifier: Apache-2.0\n")
        f.write("//\n")
        f.write("// Auto-generated by generate_data_fa.py"
                " — do not edit manually.\n\n")
        f.write("#pragma once\n\n")

        # ── Compile-time parameters ──────────────────────────────────────────
        f.write(f"#define L             {L}\n")
        f.write(f"#define S             {S}\n")
        f.write(f"#define D             {D}\n")
        f.write(f"#define B_R           {B_R}\n")
        f.write(f"#define B_C           {B_C}\n")
        f.write(f"#define BASELINE      {BASELINE}\n")
        f.write(f"#define CHECK_RESULTS {CHECK_RESULTS}\n\n")

        # ── Forward declarations ─────────────────────────────────────────────
        write_c_array(f, "Q", Q, extern=True)
        write_c_array(f, "K", K, extern=True)
        write_c_array(f, "V", V, extern=True)

        # O: output buffer (uninitialised)
        f.write(f"float O[{L * D}] __attribute__ ((aligned (4096)));\n\n")

        # ── Data definitions ─────────────────────────────────────────────────
        write_c_array(f, "Q", Q)
        write_c_array(f, "K", K)
        write_c_array(f, "V", V)

        write_c_array(f, "O_golden", O_golden)


    total = L * D
    print(f"Generated {out_path}")
    print(f"  L={L}  S={S}  D={D}  B_R={B_R}  B_C={B_C}"
          f"  baseline={BASELINE}  ({total} elements per matrix)")


if __name__ == "__main__":
    main()