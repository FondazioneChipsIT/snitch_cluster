# Generate data/data.h for the attention_forward kernel.
# Run from anywhere:
#   python sw/benchmarks/LLM/flashattention/scripts/datagen.py

import numpy as np
import os

# ──────────────────────────────────────────────
#  Configuration
# ──────────────────────────────────────────────
B  = 1    # batch size
T  = 64   # sequence length
C  = 64   # total embedding dim
NH = 1    # number of heads  →  head_size = C // NH

CHECK_RESULTS = 1
SEED          = 42
# ──────────────────────────────────────────────

assert C % NH == 0, "C must be divisible by NH"

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))


def attention_golden(
    Q: np.ndarray,  # (T, hs)
    K: np.ndarray,  # (T, hs)
    V: np.ndarray,  # (T, hs)
    scale: float,
) -> np.ndarray:
    """Scaled dot-product attention matching attention_forward semantics."""
    mask = np.triu(np.full((T, T), -np.inf), k=1)
    S_mat = (Q @ K.T) * scale + mask              # (T, T)
    S_mat -= S_mat.max(axis=-1, keepdims=True)
    P = np.exp(S_mat)
    P /= P.sum(axis=-1, keepdims=True)
    return (P @ V).astype(np.float32)       # (T, hs)


def fmt_float(v: float) -> str:
    return repr(float(v))


def write_c_array(f, name: str, data: np.ndarray, dtype_decl: str = "float",
                  align: int = 4096, extern: bool = False) -> None:
    flat = data.flatten()
    n    = len(flat)
    if extern:
        f.write(f"extern {dtype_decl} {name}[{n}]"
                f" __attribute__ ((aligned ({align})));\n\n")
        return
    f.write(f"{dtype_decl} {name}[{n}]"
            f" __attribute__ ((aligned ({align}))) = {{\n")
    for v in flat:
        f.write(f"\t{fmt_float(v)},\n")
    f.write("};\n\n")


def main():
    rng       = np.random.default_rng(SEED)
    head_size = C // NH
    scale     = 1.0 / np.sqrt(head_size)

    Q = rng.random((T, C), dtype=np.float64).astype(np.float32)
    K = rng.random((T, C), dtype=np.float64).astype(np.float32)
    V = rng.random((T, C), dtype=np.float64).astype(np.float32)

    # Run each head separately and concatenate
    O_heads = []
    for h in range(NH):
        Qh = Q[:, h * head_size:(h + 1) * head_size].astype(np.float64)
        Kh = K[:, h * head_size:(h + 1) * head_size].astype(np.float64)
        Vh = V[:, h * head_size:(h + 1) * head_size].astype(np.float64)
        O_heads.append(attention_golden(Qh, Kh, Vh, scale))
    O_golden = np.concatenate(O_heads, axis=-1)  # (T, C)

    out_dir  = os.path.normpath(os.path.join(SCRIPT_DIR, "..", "data"))
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "data.h")

    with open(out_path, "w") as f:
        f.write("// Copyright 2026 ETH Zurich and University of Bologna.\n")
        f.write("// Licensed under the Apache License, Version 2.0,"
                " see LICENSE for details.\n")
        f.write("// SPDX-License-Identifier: Apache-2.0\n")
        f.write("//\n")
        f.write("// Auto-generated by datagen.py — do not edit manually.\n\n")
        f.write("#pragma once\n\n")

        f.write(f"#define B             {B}\n")
        f.write(f"#define T             {T}\n")
        f.write(f"#define C             {C}\n")
        f.write(f"#define NH            {NH}\n")
        f.write(f"#define CHECK_RESULTS {CHECK_RESULTS}\n\n")

        write_c_array(f, "Q",        Q,        extern=True)
        write_c_array(f, "K",        K,        extern=True)
        write_c_array(f, "V",        V,        extern=True)
        write_c_array(f, "O_golden", O_golden, extern=True)

        f.write(f"float O[{T * C}] __attribute__ ((aligned (4096)));\n\n")

        write_c_array(f, "Q",        Q)
        write_c_array(f, "K",        K)
        write_c_array(f, "V",        V)
        write_c_array(f, "O_golden", O_golden)

    print(f"Generated {out_path}")
    print(f"  B={B}  T={T}  C={C}  NH={NH}  head_size={head_size}"
          f"  ({T * C} elements per matrix)")


if __name__ == "__main__":
    main()