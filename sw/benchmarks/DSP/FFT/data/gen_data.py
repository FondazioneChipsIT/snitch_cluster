import numpy as np
import os

# ===============================
# CONFIGURAZIONE
# ===============================
FFT_N = 256       # Numero di elementi FFT
RANGE = 10        # Range valori input
MIN_TWIDDLE = 0.5 # Min valore assoluto twiddle per evitare 0
OUTPUT_FILE = "data.h"

script_dir = os.path.dirname(os.path.abspath(__file__))
out_path = os.path.join(script_dir, OUTPUT_FILE)

# ===============================
# GENERAZIONE INPUT
# ===============================
# Numeri casuali tra -RANGE e +RANGE
input_data = np.random.uniform(-RANGE, RANGE, FFT_N*2)

# ===============================
# GENERAZIONE TWIDDLE (senza 0)
# ===============================
twiddle = np.exp(-2j * np.pi * np.arange(FFT_N) / FFT_N)
twiddle_real = np.real(twiddle)
twiddle_imag = np.imag(twiddle)

# Forza min valore assoluto
twiddle_real[np.abs(twiddle_real) < MIN_TWIDDLE] = MIN_TWIDDLE
twiddle_imag[np.abs(twiddle_imag) < MIN_TWIDDLE] = MIN_TWIDDLE

# Interleave real/imag per compatibilità Snitch
twiddle_data = np.empty(FFT_N*2, dtype=np.float64)
twiddle_data[0::2] = twiddle_real
twiddle_data[1::2] = twiddle_imag

# ===============================
# CALCOLO GOLDEN
# ===============================
# input complesso: interleave real/imag
input_complex = input_data[0::2] + 1j*input_data[1::2]
golden_complex = np.fft.fft(input_complex)
golden_data = np.real(golden_complex)  # solo parte reale per confronto

# ===============================
# SCRITTURA FILE data.h
# ===============================
with open(out_path, "w") as f:
    f.write("// Auto-generated by generate_data.py\n")
    f.write(f"uint32_t FFT_N = {FFT_N};\n\n")
    
    # Input
    f.write(f"double input[{FFT_N*2}] __attribute__((aligned(8))) = {{\n")
    for i, val in enumerate(input_data):
        f.write(f"    {val:.17e}")
        f.write(",\n" if i < len(input_data)-1 else "\n")
    f.write("};\n\n")
    
    # Twiddle
    f.write(f"double twiddle[{FFT_N*2}] __attribute__((aligned(8))) = \n")
    f.write("{\n")
    for i, val in enumerate(twiddle_data):
        f.write(f"    {val:.17e}")
        f.write(",\n" if i < len(twiddle_data)-1 else "\n")
    f.write("};\n\n")
    
    # Golden/output
    f.write(f"double golden[{FFT_N}] __attribute__((aligned(8))) = {{\n")
    for i, val in enumerate(golden_data):
        f.write(f"    {val:.17e}")
        f.write(",\n" if i < len(golden_data)-1 else "\n")
    f.write("};\n")

print(f"data.h generato correttamente in {out_path}")
